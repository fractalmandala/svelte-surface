import { spawn, type ChildProcess } from 'node:child_process'
import { existsSync, readFileSync, promises as fs } from 'node:fs'
import { createRequire } from 'node:module'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { detectProject } from './project.js'

const CONFIG_NAMES = ['vite.config.ts', 'vite.config.mts', 'vite.config.js', 'vite.config.mjs', 'vite.config.cts', 'vite.config.cjs']

/** Absolute path of the compiled plugin module (the dev server child cannot load `.ts`). */
export function pluginEntry(): string {
  const here = path.dirname(fileURLToPath(import.meta.url))
  for (const c of [path.join(here, '..', 'marks', 'plugin.js'), path.join(here, '..', '..', 'dist', 'marks', 'plugin.js')]) {
    if (existsSync(c)) return c
  }
  throw new Error('svelte-surface is not built: run `npm run build` first.')
}

export interface WrapperOptions {
  /** folder to write `vite.config.mjs` into; default: <tmp>/surface-temp/<id> */
  dataDir?: string
  /** options forwarded to `surfaceMarks()` (JSON-serialisable) */
  marks?: Record<string, unknown>
}

/**
 * The wrapper config: loads the project's own `vite.config` with the project's own
 * Vite and returns it with ONE extra plugin placed first. Project files are not touched.
 */
export function wrapperSource(root: string, plugin: string, marks: Record<string, unknown> = {}): string {
  return `// generated by @fractaldesign/svelte-surface. Not part of the project.
import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const ROOT = ${JSON.stringify(root)}
const NAMES = ${JSON.stringify(CONFIG_NAMES)}
const req = createRequire(path.join(ROOT, 'package.json'))
const vitePkg = req.resolve('vite/package.json')
const vite = await import(pathToFileURL(path.join(path.dirname(vitePkg), 'dist', 'node', 'index.js')).href)
const { surfaceMarks } = await import(${JSON.stringify(pathToFileURL(plugin).href)})

export default vite.defineConfig(async (env) => {
  const found = NAMES.map((n) => path.join(ROOT, n)).find((p) => existsSync(p))
  const loaded = found ? await vite.loadConfigFromFile(env, found, ROOT) : null
  const user = loaded?.config ?? {}
  return { ...user, root: ROOT, plugins: [surfaceMarks({ root: ROOT, ...${JSON.stringify(marks)} }), ...(user.plugins ?? [])] }
})
`
}

export async function writeWrapperConfig(root: string, options: WrapperOptions = {}): Promise<string> {
  const abs = path.resolve(root)
  const dir = options.dataDir ?? path.join(os.tmpdir(), 'surface-temp', Buffer.from(abs).toString('base64url').slice(-24))
  await fs.mkdir(dir, { recursive: true })
  const file = path.join(dir, 'vite.config.mjs')
  await fs.writeFile(file, wrapperSource(abs, pluginEntry(), options.marks))
  return file
}

function viteBin(root: string): string {
  const req = createRequire(path.join(root, 'package.json'))
  const pkgPath = req.resolve('vite/package.json')
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const bin = typeof pkg.bin === 'string' ? pkg.bin : pkg.bin.vite
  return path.join(path.dirname(pkgPath), bin)
}

export function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const srv = net.createServer()
    srv.once('error', reject)
    srv.listen(0, 'localhost', () => {
      const { port } = srv.address() as net.AddressInfo
      srv.close(() => resolve(port))
    })
  })
}

export interface DevOptions extends WrapperOptions {
  port?: number
  host?: string
  onLog?: (line: string) => void
  /** ms to wait for the server to answer; default 60000 */
  timeoutMs?: number
}

export interface DevServer {
  url: string
  port: number
  config: string
  process: ChildProcess
  logs: string[]
  stop(): Promise<void>
}

/** Run the project's own `vite dev` with the wrapper config. Resolves once it answers HTTP. */
export async function startDevServer(root: string, options: DevOptions = {}): Promise<DevServer> {
  const info = detectProject(root)
  if (info.kind === 'unknown') throw new Error('Not a Svelte project: needs @sveltejs/kit, or vite + svelte, in package.json.')
  const config = await writeWrapperConfig(info.root, options)
  const port = options.port ?? (await freePort())
  const host = options.host ?? 'localhost'
  const args = [viteBin(info.root), 'dev', info.root, '--config', config, '--port', String(port), '--strictPort', '--host', host]
  const logs: string[] = []
  const child = spawn(process.execPath, args, {
    cwd: info.root, // SvelteKit reads svelte.config.js from cwd
    env: { ...process.env, BROWSER: 'none', FORCE_COLOR: '0', NO_COLOR: '1' },
    stdio: ['ignore', 'pipe', 'pipe']
  })
  let exited: number | null = null
  const sink = (b: Buffer): void => {
    for (const l of b.toString().split('\n')) {
      if (!l.trim()) continue
      logs.push(l)
      options.onLog?.(l)
    }
  }
  child.stdout!.on('data', sink)
  child.stderr!.on('data', sink)
  child.on('exit', (c) => {
    exited = c ?? -1
  })

  const url = `http://${host}:${port}`
  const deadline = Date.now() + (options.timeoutMs ?? 60000)
  for (;;) {
    if (exited !== null) throw new Error(`vite exited with ${exited}:\n${logs.slice(-15).join('\n')}`)
    try {
      const r = await fetch(url + '/', { signal: AbortSignal.timeout(2000) })
      void r.body?.cancel()
      break
    } catch {
      if (Date.now() > deadline) {
        child.kill('SIGTERM')
        throw new Error(`vite did not answer on ${url} in time:\n${logs.slice(-15).join('\n')}`)
      }
      await new Promise((r) => setTimeout(r, 250))
    }
  }
  return {
    url,
    port,
    config,
    process: child,
    logs,
    stop: () =>
      new Promise<void>((resolve) => {
        if (exited !== null) return resolve()
        child.once('exit', () => resolve())
        child.kill('SIGTERM')
        setTimeout(() => child.kill('SIGKILL'), 3000).unref()
      })
  }
}
