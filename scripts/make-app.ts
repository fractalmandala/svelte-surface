// Legacy browser-window launcher: dist-app/Surface.app (`npm run app:bundle`).
// A shell script that runs this checkout's app server (app-dist/server.mjs) with the node that built it; the server
// then opens its own Chrome/Edge/Brave --app window. Quitting the window stops everything.
// Not relocatable on purpose: it points at this checkout. Prefer `npm run app:native` (WKWebView shell, self-contained).
import { chmodSync, mkdirSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const pkg = path.resolve(import.meta.dirname, '..')
if (process.platform !== 'darwin') {
  console.error('app:bundle builds a macOS .app; on other systems use `npm run app`.')
  process.exit(1)
}
if (!existsSync(path.join(pkg, 'dist', 'index.js')) || !existsSync(path.join(pkg, 'app-dist', 'server.mjs'))) throw new Error('run `npm run build:app` first')

const name = 'Surface'
const app = path.join(pkg, 'dist-app', `${name}.app`)
rmSync(app, { recursive: true, force: true })
mkdirSync(path.join(app, 'Contents', 'MacOS'), { recursive: true })

writeFileSync(path.join(app, 'Contents', 'Info.plist'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>${name}</string>
  <key>CFBundleDisplayName</key><string>${name}</string>
  <key>CFBundleIdentifier</key><string>com.fractaldesign.surface</string>
  <key>CFBundleExecutable</key><string>launcher</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
`)

const launcher = path.join(app, 'Contents', 'MacOS', 'launcher')
writeFileSync(launcher, `#!/bin/bash
# generated by scripts/make-app.ts
export PATH="${path.dirname(process.execPath)}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
mkdir -p "$HOME/Library/Logs"
cd ${JSON.stringify(pkg)} || exit 1
exec ${JSON.stringify(process.execPath)} app-dist/server.mjs --quit-on-close >> "$HOME/Library/Logs/surface.log" 2>&1
`)
chmodSync(launcher, 0o755)
try { execFileSync('codesign', ['--force', '--sign', '-', app], { stdio: 'ignore' }) } catch {}
console.log(`built: ${app}\nDouble-click it, or: open "${app}"\nLog: ~/Library/Logs/surface.log`)
